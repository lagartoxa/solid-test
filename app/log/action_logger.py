"""
Action logger - the single entry point for writing the logs table.

The goal of the logs is to track errors later. Each entry gets the id of the
current request, the User-Id header and payloads converted to JSON with the
sensitive keys masked.
"""

import json
import logging
import time
import traceback
import uuid
from contextlib import contextmanager
from dataclasses import dataclass
from typing import Any, Iterator, Optional

from flask import current_app, g, has_request_context, request

from app.db.constants import MASK, SENSITIVE_KEYS, ChangeOperation, LogAction
from app.db.models.log import Log

# No underscore: some servers (nginx, gunicorn) drop headers with underscores.
USER_ID_HEADER = "User-Id"

# Used only when a log entry can't be saved in the database.
fallback_logger = logging.getLogger(__name__)


@dataclass
class ExternalCall:
    """What an external service returned, set by the caller inside ActionLogger.external_call."""

    received: Any = None


class ActionLogger:
    """
    Singleton that builds and saves log entries.

    API requests and external calls are saved in their own transaction, so
    they are kept even when the request fails and rolls back. Database
    changes are only built here (db_change_entry): the repository saves them
    in the same transaction as the change.
    """

    _instance: Optional["ActionLogger"] = None

    def __new__(cls) -> "ActionLogger":
        """Always return the same instance."""
        if cls._instance is None:
            cls._instance = super().__new__(cls)

        return cls._instance

    def log_api_request(
        self,
        method: str,
        path: str,
        request_payload: Any,
        status_code: int,
        response_payload: Any,
        error: Optional[str],
        duration_ms: int,
        log_id: Optional[uuid.UUID] = None,
    ) -> None:
        """
        Save a request received by the API and the response it sent.

        Args:
            method: HTTP method
            path: Request path
            request_payload: Headers, query string and body received
            status_code: Response status code
            response_payload: Response body sent
            error: Traceback of an unexpected error, if any
            duration_ms: Time to handle the request
            log_id: Id for the log row, when it was already given to the
                client (unexpected errors); generated by the database otherwise
        """
        self._save(
            self._entry(
                LogAction.API_REQUEST,
                f"{method} {path}",
                request_payload=request_payload,
                response_payload=response_payload,
                id=log_id,
                status_code=status_code,
                error=error,
                duration_ms=duration_ms,
            )
        )

    def log_external_call(
        self,
        service: str,
        operation: str,
        sent: Any,
        received: Any,
        error: Optional[str],
        duration_ms: int,
    ) -> None:
        """
        Save a call to an external service.

        Args:
            service: Service name (e.g. "payment_provider")
            operation: Operation called (e.g. "charge")
            sent: Payload sent to the service
            received: Payload received from the service
            error: Traceback of the error, if the call failed
            duration_ms: Time the call took
        """
        self._save(
            self._entry(
                LogAction.EXTERNAL_CALL,
                f"{service}.{operation}",
                request_payload=sent,
                response_payload=received,
                error=error,
                duration_ms=duration_ms,
            )
        )

    @contextmanager
    def external_call(self, service: str, operation: str, sent: Any) -> Iterator[ExternalCall]:
        """
        Measure and log an external call, including its error.

        Usage:
            with action_logger.external_call("payment_provider", "charge", payload) as call:
                call.received = provider.charge(payload)

        The error, if any, is logged and raised again.
        """
        call = ExternalCall()
        error = None
        started_at = time.perf_counter()

        try:
            yield call
        except Exception:
            error = traceback.format_exc()
            raise
        finally:
            self.log_external_call(
                service, operation, sent, call.received, error, elapsed_ms(started_at)
            )

    def db_change_entry(
        self,
        table: str,
        record_id: uuid.UUID,
        operation: ChangeOperation,
        before: Optional[dict[str, Any]],
        after: Optional[dict[str, Any]],
    ) -> Log:
        """
        Build (not save) the log entry of a database change.

        Args:
            table: Table name
            record_id: Id of the changed record
            operation: Kind of change
            before: Values before the change
            after: Values after the change

        Returns:
            Log entry for the repository to save
        """
        return self._entry(
            LogAction.DB_CHANGE,
            table,
            request_payload={"before": before, "after": after},
            record_id=record_id,
            operation=operation.value,
        )

    def _entry(
        self,
        action: LogAction,
        target: str,
        request_payload: Any = None,
        response_payload: Any = None,
        **fields: Any,
    ) -> Log:
        """Build a log entry with the request context and the masked payloads."""
        request_id, user_id = self._request_context()

        return Log(
            action=action.value,
            target=target,
            request_id=request_id,
            user_id=user_id,
            request_payload=to_masked_json(request_payload),
            response_payload=to_masked_json(response_payload),
            **fields,
        )

    def _save(self, entry: Log) -> None:
        """
        Save an entry in its own session and transaction.

        A failure to save never breaks the request: it goes to the Python logger.
        """
        # Imported here: the repositories use this logger, so importing at
        # module level would be circular.
        from app.db.repositories.log_repository import LogRepository

        try:
            with LogRepository(current_app.extensions["session_factory"]()) as repo:
                repo.add(entry)
        except Exception:
            fallback_logger.exception("Could not save log %s %s", entry.action, entry.target)

    @staticmethod
    def _request_context() -> tuple[Optional[uuid.UUID], Optional[str]]:
        """Request id and User-Id header of the current request (None outside requests)."""
        if not has_request_context():
            return None, None

        return g.get("request_id"), request.headers.get(USER_ID_HEADER)


def to_masked_json(payload: Any) -> Any:
    """
    Convert a payload to JSON-compatible data with the sensitive keys masked.

    Values JSON can't hold (UUID, Decimal, datetime, ...) become strings.
    """
    if payload is None:
        return None

    return mask_sensitive(json.loads(json.dumps(payload, default=str)))


def mask_sensitive(value: Any) -> Any:
    """Replace the value of every sensitive key, at any depth, with MASK."""
    if isinstance(value, dict):
        return {
            key: MASK if str(key).lower() in SENSITIVE_KEYS else mask_sensitive(item)
            for key, item in value.items()
        }

    if isinstance(value, list):
        return [mask_sensitive(item) for item in value]

    return value


def elapsed_ms(started_at: float) -> int:
    """Milliseconds since started_at (a time.perf_counter() value)."""
    return round((time.perf_counter() - started_at) * 1000)


action_logger = ActionLogger()
